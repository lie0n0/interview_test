function slug(s) {
  return s.replace(/[^가-힣a-zA-Z0-9]/g, '_').replace(/_+/g, '_').toLowerCase();
}

const out = { universities: [], defaultWeights: T.etc.w };
const seenNames = new Set();

for (const [uniId, uniName, dispKey, deptNames] of RAW) {
  if (seenNames.has(uniName)) {
    console.warn(`⚠️ 중복 대학 건너뜀: ${uniName}`);
    continue;
  }
  seenNames.add(uniName);

  const depts = deptNames.map((dName, i) => {
    const tmpl = getTmpl(dName);
    return {
      id: slug(dName) + '_' + i,
      name: dName,
      passage: tmpl.passage(dName),
      modelAnswerHint: tmpl.hint,
      disposition: tmpl.disp,
      weights: { ...tmpl.w },
    };
  });

  out.universities.push({
    id: uniId,
    name: uniName,
    departments: depts,
  });
}

out.universities.sort((a, b) => a.name.localeCompare(b.name, 'ko'));

// 출력
const outPath = path.join(__dirname, 'universities.json');
fs.writeFileSync(outPath, JSON.stringify(out, null, 2), 'utf8');

// 통계
let totalDepts = 0;
for (const u of out.universities) totalDepts += u.departments.length;
console.log(`✅ 생성 완료: ${out.universities.length}개 대학, ${totalDepts}개 학과`);
console.log(`   출력: ${outPath}`);
